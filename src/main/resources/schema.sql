-- ==========================================================================
-- 植物光配方（pf-light-1）
-- 配方按"品种 + 生长阶段"配置：每个阶段含若干时段，时段内定义光谱比例与亮度。
-- 版本只追加；新版本只影响"未开始"的阶段，已开始阶段沿用进入时的版本快照。
-- 配方整点按棚区下发；下发时冻结快照，历史执行不随后续改配方变化；失败设备进重试队列。
-- ==========================================================================

-- 生长阶段口径（与 GrowthStage 枚举同一处定义）：
-- SEEDLING 幼苗 / VEGETATIVE 营养生长 / FLOWERING 开花 / FRUITING 结果
-- 阶段边界按"批次生长进度 0~100"统一归属：[from_progress, to_progress)，左闭右开。

-- 光配方（头表，按品种版本化；同一品种只允许一个生效版本，历史版本保留）
CREATE TABLE IF NOT EXISTS t_pf_light_recipe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_code VARCHAR(40) NOT NULL,
    variety_id BIGINT NOT NULL,
    version_no INT NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'DRAFT',
    base_from_version_id BIGINT,
    published_at TIMESTAMP,
    effective_at TIMESTAMP,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_light_recipe_ver UNIQUE (variety_id, version_no)
);
CREATE INDEX IF NOT EXISTS idx_pf_light_recipe_variety ON t_pf_light_recipe (variety_id, status);

-- 配方阶段（生长阶段口径；进度边界左闭右开，同一配方内阶段不重叠、首尾相接覆盖 0~100）
CREATE TABLE IF NOT EXISTS t_pf_light_recipe_stage (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL,
    stage_code VARCHAR(16) NOT NULL,
    from_progress INT NOT NULL,
    to_progress INT NOT NULL,
    default_brightness_pct INT NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_light_stage UNIQUE (recipe_id, stage_code)
);

-- 配方时段（当地时间 HH:mm 左闭右开，允许跨午夜；不亮时段（关灯）brightness_pct=0）
CREATE TABLE IF NOT EXISTS t_pf_light_recipe_slot (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage_id BIGINT NOT NULL,
    start_minute INT NOT NULL,
    end_minute INT NOT NULL,
    brightness_pct INT NOT NULL,
    ratio_red_pct INT NOT NULL,
    ratio_green_pct INT NOT NULL,
    ratio_blue_pct INT NOT NULL,
    ratio_white_pct INT NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_light_slot UNIQUE (stage_id, start_minute)
);

-- 批次阶段版本绑定：批次每次"进入"一个阶段时冻结一条；新版本只影响未开始阶段。
-- status: ACTIVE 当前阶段 / FINISHED 已结束（历史执行快照，不再改动）
CREATE TABLE IF NOT EXISTS t_pf_batch_stage_binding (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    stage_code VARCHAR(16) NOT NULL,
    recipe_id BIGINT NOT NULL,
    recipe_version_no INT NOT NULL,
    progress_at_entry INT NOT NULL,
    entered_at TIMESTAMP NOT NULL,
    left_at TIMESTAMP,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_stage_binding_active UNIQUE (batch_id, stage_code, status)
);
CREATE INDEX IF NOT EXISTS idx_pf_stage_binding_batch ON t_pf_batch_stage_binding (batch_id, status);

-- 光控下发流水：按棚区（温室+分区）整点下发；payload_json 为配方快照，历史执行永不变形。
-- result: SUCCESS 成功 / FAILED 失败（设备进重试队列）
CREATE TABLE IF NOT EXISTS t_pf_light_dispatch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    greenhouse_id BIGINT NOT NULL,
    zone_id BIGINT,
    batch_id BIGINT NOT NULL,
    stage_code VARCHAR(16),
    slot_start_minute INT,
    recipe_id BIGINT,
    recipe_version_no INT,
    source VARCHAR(16) NOT NULL,
    payload_json CLOB NOT NULL,
    planned_at TIMESTAMP NOT NULL,
    dispatched_at TIMESTAMP,
    result VARCHAR(16),
    fail_reason VARCHAR(255),
    operator_id BIGINT NOT NULL,
    operator_name VARCHAR(64) NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_pf_light_dispatch_plan ON t_pf_light_dispatch (planned_at, result);

-- 失败重试队列：同一失败下发只占一条待处理记录，成功后 DONE。
-- status: PENDING 待重试 / DONE 已成功 / GIVEN_UP 超过上限放弃
CREATE TABLE IF NOT EXISTS t_pf_light_dispatch_retry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispatch_id BIGINT NOT NULL,
    greenhouse_id BIGINT NOT NULL,
    zone_id BIGINT,
    next_retry_at TIMESTAMP NOT NULL,
    attempt_count INT NOT NULL DEFAULT 0,
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    last_fail_reason VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_light_retry_dispatch UNIQUE (dispatch_id)
);
CREATE INDEX IF NOT EXISTS idx_pf_light_retry_due ON t_pf_light_dispatch_retry (status, next_retry_at);

