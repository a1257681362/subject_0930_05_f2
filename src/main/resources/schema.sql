-- H2 本地文件数据库初始化脚本。
-- 骨架版本表
CREATE TABLE IF NOT EXISTS t_evops_schema_version (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_no VARCHAR(32) NOT NULL,
    description VARCHAR(255) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_evops_schema_version UNIQUE (version_no)
);

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('base-0', 'EVOPS 初始工作区');

MERGE INTO t_evops_schema_version (version_no, description)
KEY (version_no)
VALUES ('pf-ledger-1', '植物工厂种植批次台账：温室/分区/品种/播种盘/批次/转棚/养护/采收/质检');

-- ==========================================================================
-- 植物工厂种植台账（起步阶段：建档、播种、养护、采收、质检；销售结算后续再接）
-- ==========================================================================

-- 业务编号序列（重启不回退，保证批次号/采收单号全局唯一）
CREATE SEQUENCE IF NOT EXISTS seq_pf_batch_no START WITH 1001;
CREATE SEQUENCE IF NOT EXISTS seq_pf_harvest_no START WITH 1001;

-- 操作者（create_by/update_by 关联本表；0=系统，供定时任务兜底，保证不丢操作者）
CREATE TABLE IF NOT EXISTS t_pf_operator (
    id BIGINT PRIMARY KEY,
    operator_no VARCHAR(32) NOT NULL,
    name VARCHAR(64) NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_pf_operator_no UNIQUE (operator_no)
);
MERGE INTO t_pf_operator (id, operator_no, name, status) KEY (id) VALUES (0, 'SYSTEM', '系统（定时任务）', 'ACTIVE');
MERGE INTO t_pf_operator (id, operator_no, name, status) KEY (id) VALUES (1, 'bootstrap', '建档管理员', 'ACTIVE');

-- 温室：记录光照与营养液循环配置
CREATE TABLE IF NOT EXISTS t_pf_greenhouse (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gh_code VARCHAR(32) NOT NULL,
    gh_name VARCHAR(64) NOT NULL,
    light_source VARCHAR(128),
    photoperiod_hours INT,
    ppfd INT,
    nutrient_cycle_mode VARCHAR(64),
    nutrient_ec DECIMAL(5,2),
    nutrient_ph DECIMAL(4,2),
    cycle_interval_min INT,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_gh_code UNIQUE (gh_code)
);

-- 设备分区（隶属于温室）
CREATE TABLE IF NOT EXISTS t_pf_zone (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    greenhouse_id BIGINT NOT NULL,
    zone_code VARCHAR(32) NOT NULL,
    zone_name VARCHAR(64) NOT NULL,
    function_type VARCHAR(64),
    equipment_desc VARCHAR(255),
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_zone_code UNIQUE (greenhouse_id, zone_code)
);

-- 品种
CREATE TABLE IF NOT EXISTS t_pf_variety (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variety_code VARCHAR(32) NOT NULL,
    variety_name VARCHAR(64) NOT NULL,
    category VARCHAR(64),
    grow_days INT NOT NULL DEFAULT 30,
    status VARCHAR(16) NOT NULL DEFAULT 'ACTIVE',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_variety_code UNIQUE (variety_code)
);

-- 播种盘
CREATE TABLE IF NOT EXISTS t_pf_tray (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tray_code VARCHAR(32) NOT NULL,
    spec VARCHAR(64),
    hole_count INT,
    status VARCHAR(16) NOT NULL DEFAULT 'IDLE',
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_tray_code UNIQUE (tray_code)
);

-- 种植批次（关联品种、播种盘、计划采收日；批次号唯一）
CREATE TABLE IF NOT EXISTS t_pf_batch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_no VARCHAR(40) NOT NULL,
    variety_id BIGINT NOT NULL,
    tray_id BIGINT NOT NULL,
    greenhouse_id BIGINT NOT NULL,
    zone_id BIGINT,
    sow_date DATE NOT NULL,
    planned_harvest_date DATE NOT NULL,
    actual_harvest_date DATE,
    status VARCHAR(16) NOT NULL DEFAULT 'SOWN',
    startup_flag VARCHAR(1) NOT NULL DEFAULT 'N',
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_batch_no UNIQUE (batch_no)
);
CREATE INDEX IF NOT EXISTS idx_pf_batch_status ON t_pf_batch (status);

-- 转棚留痕（只追加，不修改；快照操作者与棚/分区）
CREATE TABLE IF NOT EXISTS t_pf_batch_relocation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    seq_no INT NOT NULL,
    from_greenhouse_id BIGINT,
    from_zone_id BIGINT,
    to_greenhouse_id BIGINT NOT NULL,
    to_zone_id BIGINT,
    reason VARCHAR(255),
    operator_id BIGINT NOT NULL,
    operator_name VARCHAR(64) NOT NULL,
    relocated_at TIMESTAMP NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_relocation_seq UNIQUE (batch_id, seq_no)
);

-- 养护记录（光照巡检、营养液循环巡检、设备巡检等）
CREATE TABLE IF NOT EXISTS t_pf_care_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL,
    care_type VARCHAR(16) NOT NULL,
    content VARCHAR(255) NOT NULL,
    reading DECIMAL(10,2),
    unit VARCHAR(16),
    log_time TIMESTAMP NOT NULL,
    operator_id BIGINT NOT NULL,
    operator_name VARCHAR(64) NOT NULL,
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_pf_care_batch ON t_pf_care_log (batch_id);

-- 采收单（等级、重量、去向；采收单号唯一）
CREATE TABLE IF NOT EXISTS t_pf_harvest_order (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    harvest_no VARCHAR(40) NOT NULL,
    batch_id BIGINT NOT NULL,
    grade VARCHAR(16) NOT NULL,
    weight_kg DECIMAL(10,2) NOT NULL,
    destination VARCHAR(128) NOT NULL,
    harvest_date DATE NOT NULL,
    qc_status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    operator_id BIGINT NOT NULL,
    operator_name VARCHAR(64) NOT NULL,
    remark VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_harvest_no UNIQUE (harvest_no)
);
CREATE INDEX IF NOT EXISTS idx_pf_harvest_batch ON t_pf_harvest_order (batch_id);

-- 质检结果（一张采收单至多一条质检）
CREATE TABLE IF NOT EXISTS t_pf_quality_check (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    harvest_id BIGINT NOT NULL,
    result VARCHAR(16) NOT NULL,
    inspector_id BIGINT NOT NULL,
    inspector_name VARCHAR(64) NOT NULL,
    check_time TIMESTAMP NOT NULL,
    note VARCHAR(255),
    create_by BIGINT,
    create_time TIMESTAMP,
    update_by BIGINT,
    update_time TIMESTAMP,
    CONSTRAINT uk_pf_qc_harvest UNIQUE (harvest_id)
);

